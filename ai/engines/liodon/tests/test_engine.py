def test_health_endpoint_reports_loaded_model(synthetic_image_bytes):
    from app.main import app

    client = TestClient(app)
    h = client.get("/health").json()
    assert h["status"] == "ok"
    assert h["model_loaded"] is True
    assert h["model_name"] == "liodon"
    assert h["model_version"] == "1.0.0"
    assert h["model_license"] == "CC-BY-NC-4.0"
    assert h["model_source"].startswith("https://huggingface.co/liodon-ai/dental-panoramic-detector")
    assert h["device"] == "cpu"
    assert h["runtime"]["execution_provider"] == "CPUExecutionProvider"
    assert h["is_standin_not_liodon"] is True
    assert h["model_checksum_verified"] is True
    assert h["tensor_input"]["shape"] == [1, 3, 640, 640]
    assert h["tensor_output"]["shape"] == [1, 7, 8400]


def test_infer_endpoint_returns_structured_findings(synthetic_image_bytes):
    from app.main import app

    client = TestClient(app)
    r = client.post(
        "/infer",
        json={"image": base64.b64encode(synthetic_image_bytes).decode()},
    )
    assert r.status_code == 200
    body = r.json()
    assert body["detection_count"] == 3
    assert body["is_standin_not_liodon"] is True
    assert body["device"] == "cpu"
    assert body["model"]["model_sha256"]
    assert body["model"]["model_version"] == "1.0.0"
    assert body["annotated_png_hex"]
    for d in body["detections"]:
        assert d["condition"] in KNOWN_CLASSES
        assert 0.0 <= d["confidence"] <= 1.0


def test_infer_endpoint_rejects_invalid_base64():
    from app.main import app

    client = TestClient(app)
    r = client.post("/infer", json={"image": "!!not-base64!!"})
    assert r.status_code == 400
