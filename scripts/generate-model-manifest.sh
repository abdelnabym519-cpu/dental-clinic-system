#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# scripts/generate-model-manifest.sh
#
# Regenerates ai-validation/models.sha256 from the weight files that are
# actually present on disk. Run it once after downloading/placing the local AI
# model weights, then commit the manifest (names + digests are not secrets).
#
# It NEVER writes an empty manifest over a populated one: if no weight file is
# found it exits non-zero and leaves the previous manifest untouched, so a
# misconfigured run can never silently "pass" an integrity check.
# ---------------------------------------------------------------------------
set -u

cd "$(dirname "$0")/.." || exit 1

OUT="ai-validation/models.sha256"
HEADER='# ai-validation/models.sha256 — integrity manifest for local AI model weights.
#
# File NAMES and SHA-256 DIGESTS are not secrets. This manifest is committed on
# purpose so that `scripts/verify-ai.sh` can run `sha256sum -c` on any machine
# and prove the weights are the ones that were validated.
#
# Generated by: ./scripts/generate-model-manifest.sh
#
# VERIFY:
#     ( cd ai-validation && sha256sum -c models.sha256 )
#
# RULES (MASTER-DENTORA-ALL-IN-ONE.md 4.8): digests are NEVER edited to make a
# check pass. The engines refuse to start on a checksum mismatch by design; a
# mismatch means the file changed, and that must be investigated, not silenced.
'

FOUND=$(find ai-validation -type f \
  \( -name '*.pt' -o -name '*.pth' -o -name '*.onnx' -o -name '*.bin' \
     -o -name '*.safetensors' -o -name '*.ckpt' -o -name '*.engine' \) \
  2>/dev/null | sort)

if [ -z "$FOUND" ]; then
  echo "generate-model-manifest: NO weight files found under ai-validation/."
  echo "  Manifest left UNCHANGED at $OUT (refusing to write an empty manifest)."
  echo "  Place the model weights first, then re-run this script."
  exit 1
fi

COUNT=$(printf '%s\n' "$FOUND" | wc -l | tr -d ' ')
{
  printf '%s\n' "$HEADER"
  printf '%s\n' "$FOUND" | while IFS= read -r f; do sha256sum "$f"; done
} > "$OUT"

echo "generate-model-manifest: wrote $COUNT entries to $OUT"
echo "  verify with: ( cd ai-validation && sha256sum -c models.sha256 )"
